    private void btnInserirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInserirActionPerformed

        consulta = new Consulta(Integer.parseInt(txtCodigo.getText()), ftfData.getText());
        consulta.setValor(Double.parseDouble(txtValor.getText()));
        consulta.setMedico(medico);
        daoConsulta.inserir(consulta, ftfCPFpaciente.getText());

        txtCodigo.setText("");
        ftfCPFmedico.setText("");
        ftfCPFpaciente.setText("");
        ftfData.setText("");
        txtValor.setText("");
        lblCpfMedico.setText("");
        lblCpfPaciente.setText("");

        ftfCPFmedico.setEnabled(false);
        ftfCPFpaciente.setEnabled(false);
        ftfData.setEnabled(false);
        txtValor.setEnabled(false);

        btnConsultarMedico.setEnabled(false);
        btnConsultarPaciente.setEnabled(false);

        btnConsultar.setEnabled(true);
        btnInserir.setEnabled(false);
        btnAlterar.setEnabled(false);
        btnExcluir.setEnabled(false);

        consulta = null;
        medico = null;

        txtCodigo.requestFocus();

    }//GEN-LAST:event_btnInserirActionPerformed


