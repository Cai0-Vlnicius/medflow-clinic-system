    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed

        consulta = daoConsulta.consultar(Integer.parseInt(txtCodigo.getText()));
        if (consulta == null) {

            txtCodigo.setEnabled(false);
            ftfCPFmedico.setEnabled(true);
            btnConsultar.setEnabled(false);
            btnInserir.setEnabled(false);
            btnAlterar.setEnabled(false);
            btnExcluir.setEnabled(false);
            btnConsultarMedico.setEnabled(true);
            ftfCPFmedico.requestFocus();

        } else {
            medico = consulta.getMedico();

            String cpfPaciente = daoPaciente.CpfPaciente(consulta.getCodigo());
            String nomePaciente = daoPaciente.NomePaciente(cpfPaciente);

            ftfCPFmedico.setText(medico.getCpf());
            ftfCPFpaciente.setText(cpfPaciente);
            ftfData.setText(consulta.getData());
            txtValor.setText(String.valueOf(consulta.getValor()));

            lblCpfMedico.setText(medico.getNome());
            lblCpfPaciente.setText(nomePaciente);

            txtCodigo.setEnabled(false);
            ftfCPFmedico.setEnabled(false);
            ftfCPFpaciente.setEnabled(false);
            ftfData.setEnabled(true);
            txtValor.setEnabled(true);

            ftfCPFmedico.requestFocus();

            btnConsultar.setEnabled(false);
            btnInserir.setEnabled(false);
            btnAlterar.setEnabled(true);
            btnExcluir.setEnabled(true);
        }

    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        if (JOptionPane.showConfirmDialog(null, "Confirma Alteração?") == 0) {

            consulta.setData(ftfData.getText());
            consulta.setValor(Double.parseDouble(txtValor.getText()));
            ftfData.requestFocus();
            daoConsulta.alterar(consulta);
        }

        txtCodigo.setText("");
        ftfData.setText("");
        txtValor.setText("");
        ftfCPFmedico.setText("");
        ftfCPFpaciente.setText("");
        lblCpfMedico.setText("");
        lblCpfPaciente.setText("");

        txtCodigo.requestFocus();

        txtValor.setEnabled(false);
        ftfData.setEnabled(false);
        btnConsultar.setEnabled(true);
        btnInserir.setEnabled(false);
        btnAlterar.setEnabled(false);
        btnExcluir.setEnabled(false);
        txtCodigo.setEnabled(true);
    }//GEN-LAST:event_btnAlterarActionPerformed

